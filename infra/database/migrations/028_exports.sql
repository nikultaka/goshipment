-- =====================================================
-- 028_exports.sql
-- Asynchronous Export Jobs (CSV, background workers)
-- =====================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- =====================================================
-- ENUMS
-- =====================================================

CREATE TYPE export_status AS ENUM (
    'queued',
    'processing',
    'ready',
    'failed',
    'expired'
);

CREATE TYPE export_delivery_method AS ENUM (
    'download',
    'email'
);

-- =====================================================
-- EXPORTS
-- =====================================================
-- One row per export job
-- Durable across refresh, logout, disconnect
-- Files are generated by background workers
-- =====================================================

CREATE TABLE exports (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

    -- Ownership
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- What is being exported
    export_type VARCHAR(50) NOT NULL,   -- wallet_transactions, shipments, invoices, etc.
    format VARCHAR(10) NOT NULL DEFAULT 'csv',

    -- Delivery
    delivery_method export_delivery_method NOT NULL DEFAULT 'download',
    email_sent_at TIMESTAMP,

    -- Status
    status export_status NOT NULL DEFAULT 'queued',
    error_message TEXT,

    -- File details (set when ready)
    file_id UUID REFERENCES files(id) ON DELETE SET NULL,
    file_size BIGINT,
    row_count INTEGER,

    -- Retention
    expires_at TIMESTAMP,

    -- Audit
    created_at TIMESTAMP DEFAULT NOW(),
    completed_at TIMESTAMP
);

-- =====================================================
-- INDEXES
-- =====================================================

CREATE INDEX idx_exports_user_created
    ON exports (user_id, created_at DESC);

CREATE INDEX idx_exports_status
    ON exports (status);

CREATE INDEX idx_exports_type
    ON exports (export_type);

CREATE INDEX idx_exports_file_id ON exports(file_id);
-- =====================================================
-- NOTES
-- =====================================================
-- 1. Exports are created immediately with status = 'queued'
-- 2. Background workers update:
--    - status → processing → ready / failed
--    - file_path, file_size, row_count
-- 3. Email delivery does NOT replace download availability
-- 4. Files should be deleted after expires_at by cleanup job
-- 5. UI reads ONLY from this table for Exports page
-- =====================================================
